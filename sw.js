self.addEventListener('install', (event) => {
    event.waitUntil(
        caches.open(CACHE)
            .then(cache => cache.addAll(PRECACHE))
            .then(() => self.skipWaiting())
    );
});

self.addEventListener('activate', (event) => {
    event.waitUntil(
        caches.keys()
            .then(keys => Promise.all(keys
                .filter(k => k.startsWith('koala-artillery-') && k !== CACHE)
                .map(k => caches.delete(k))))
            .then(() => self.clients.claim())
    );
});

self.addEventListener('fetch', (event) => {
    const req = event.request;
    if (req.method !== 'GET') return;
    const url = new URL(req.url);
    if (!url.protocol.startsWith('http')) return;

    event.respondWith((async () => {
        const cache = await caches.open(CACHE);
        const cached = await cache.match(req, { ignoreSearch: url.origin === self.location.origin });

        const network = fetch(req).then(res => {
            // Opaque cross-origin responses (status 0) are fine to cache too
            if (res && (res.ok || res.type === 'opaque')) {
                cache.put(req, res.clone());
            }
            return res;
        }).catch(() => null);

        if (cached) {
            // Refresh in the background; serve the cached copy now
            event.waitUntil(network);
            return cached;
        }
        const res = await network;
        if (res) return res;
        // Offline navigation falls back to the cached shell
        if (req.mode === 'navigate') {
            const shell = await cache.match('./index.html');
            if (shell) return shell;
        }
        return new Response('Offline', { status: 503, statusText: 'Offline' });
    })());
});
