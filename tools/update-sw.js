#!/usr/bin/env node
/**
 * Regenerate the service worker's precache list and bump its cache version.
 *
 *   node tools/update-sw.js
 *
 * Run after adding, removing or changing game files so installed copies
 * (PWA / offline play) pick up the new version. Everything the game needs
 * to start and play offline is precached; music and ambience (large) are
 * cached the first time they play.
 */

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const root = path.resolve(__dirname, '..');
const SW = path.join(root, 'sw.js');

// Folders/files to precache (relative to the repo root)
const INCLUDE = ['index.html', 'manifest.webmanifest', 'styles', 'js', 'maps',
    'assets/icons', 'assets/audio/sfx', 'assets/audio/voice'];
const INCLUDE_ROOT_ASSETS = /^assets\/[^/]+\.(png|jpg|webp)$/;

function walk(rel) {
    const abs = path.join(root, rel);
    if (!fs.existsSync(abs)) return [];
    if (fs.statSync(abs).isFile()) return [rel];
    return fs.readdirSync(abs).flatMap(name => walk(path.posix.join(rel, name)));
}

const files = [
    ...INCLUDE.flatMap(walk),
    ...fs.readdirSync(path.join(root, 'assets'))
        .map(n => 'assets/' + n)
        .filter(p => INCLUDE_ROOT_ASSETS.test(p))
].sort();

// Version = hash of the precached content, so it changes only when files do
const hash = crypto.createHash('sha1');
for (const f of files) hash.update(f).update(fs.readFileSync(path.join(root, f)));
const version = hash.digest('hex').slice(0, 10);

const sw = fs.readFileSync(SW, 'utf8');
const list = files.map(f => `    './${f}'`).join(',\n');
const out = sw
    .replace(/const CACHE_VERSION = '[^']*';/, `const CACHE_VERSION = '${version}';`)
    .replace(/\/\/ PRECACHE-START[\s\S]*\/\/ PRECACHE-END/,
        `// PRECACHE-START (generated by tools/update-sw.js)\nconst PRECACHE = [\n    './',\n${list}\n];\n// PRECACHE-END`);
fs.writeFileSync(SW, out);
console.log(`sw.js: ${files.length} files precached, cache version ${version}`);
